# ---- variable construction (as in Table1.do / Figure1.do / Figure2.do) -------------------
prep <- function(d) {
  d <- copy(d)
  # family orientation for Table 1: mean of parents, siblings, adult children, extended family
  d[, rw_family := rowMeans(cbind(rw_parents, rw_siblings, rw_children, rw_fam), na.rm = TRUE)]
  d[is.nan(rw_family), rw_family := NA]
  # close family for Figure 2: parents, siblings, adult children
  d[, rw_close := rowMeans(cbind(rw_parents, rw_siblings, rw_children), na.rm = TRUE)]
  d[is.nan(rw_close), rw_close := NA]
  d[, canadian := as.numeric(country == "CA")]
  d[, discuss_close := as.numeric(discuss_parents == 1 | discuss_siblings == 1 | discuss_children == 1)]
  # clusters: country x survey week (x family level, as in the paper's Table 1 col. 1)
  d[, cl_week := .GRP, by = .(country, time)]
  d[, cl_fam := .GRP, by = .(country, time, rw_family)]
  # event-time bins in weeks relative to Thanksgiving: -2 (<= -14 days) ... 3 (>= 21 days)
  d[, ds2 := pmin(pmax(days_since, -14), 21)]
  d[, ev := fifelse(ds2 == 21, 3, floor(ds2 / 7))]
  d[, ev := factor(ev, levels = c(-1, -2, 0, 1, 2, 3))]     # -1 is the reference week
  d[]
}

