# ---- wild cluster bootstrap (WCR, Rademacher weights, null imposed) ------------------------
# Tests H0: coefficient on `term` = 0 in a fixest model with individual fixed effects,
# clustering by `cl` (a vector aligned with the estimation sample). Works through the
# Frisch-Waugh-Lovell theorem: demean by id, partial out the other regressors.
wild_p <- function(m, data, term, cl_var, B = 9999, seed = 20261130) {
  rows <- obs(m)
  X  <- model.matrix(m, type = "rhs", collin.rm = TRUE)
  y  <- model.matrix(m, type = "lhs")
  id <- data$id[rows]; cl <- data[[cl_var]][rows]
  Xd <- demean(X, f = id); yd <- as.numeric(demean(y, f = id))
  W  <- Xd[, colnames(Xd) != term, drop = FALSE]
  Q  <- qr.Q(qr(W))
  res <- function(v) v - Q %*% crossprod(Q, v)
  xt <- as.numeric(res(Xd[, term])); yt <- as.numeric(res(yd))
  sxx <- sum(xt^2); g <- as.integer(factor(cl)); G <- max(g)
  tstat <- function(z) {                 # z: n x r matrix of partialled-out outcomes
    b <- colSums(xt * z) / sxx
    e <- z - outer(xt, b)
    sc <- rowsum(xt * e, g)              # G x r cluster scores
    b / (sqrt(colSums(sc^2)) / sxx)
  }
  t0 <- tstat(matrix(yt))
  set.seed(seed); tb <- numeric(0)
  for (chunk in split(seq_len(B), ceiling(seq_len(B) / 500))) {
    V <- matrix(sample(c(-1, 1), G * length(chunk), replace = TRUE), G)
    Z <- yt * V[g, , drop = FALSE]       # restricted residuals (beta = 0) times weights
    Z <- Z - Q %*% crossprod(Q, Z)
    tb <- c(tb, tstat(Z))
  }
  c(t = t0, p = mean(abs(tb) >= abs(t0)), G = G)
}
